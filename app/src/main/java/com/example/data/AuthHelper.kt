private const val TAG = "Auth"

internal fun FirebaseAuth.authStateFlow(): Flow<FirebaseUser?> = callbackFlow {
  val listener = FirebaseAuth.AuthStateListener { auth -> trySend(auth.currentUser) }
  addAuthStateListener(listener)
  awaitClose { removeAuthStateListener(listener) }
}

private fun safeFirebaseAuth(context: Context): FirebaseAuth? =
  runCatching {
    if (FirebaseApp.getApps(context.applicationContext).isEmpty()) {
      FirebaseApp.initializeApp(context.applicationContext)
    }
    Firebase.auth
  }.getOrNull()

fun attemptAutoSignIn(
  context: Context,
  credentialManager: CredentialManager,
  onAuthSuccess: () -> Unit,
  onUnauthenticated: () -> Unit,
  scope: CoroutineScope,
) {
  val auth = safeFirebaseAuth(context)
  if (auth == null) {
    onUnauthenticated()
    return
  }
  if (auth.currentUser != null) {
    onAuthSuccess()
    return
  }
  val clientId =
    try {
      context.getString(R.string.default_web_client_id)
    } catch (_: Exception) {
      onUnauthenticated()
      return
    }
  val googleIdOption =
    GetGoogleIdOption.Builder()
      .setFilterByAuthorizedAccounts(true)
      .setServerClientId(clientId)
      .setAutoSelectEnabled(true)
      .build()
  val request = GetCredentialRequest.Builder().addCredentialOption(googleIdOption).build()
  scope.launch {
    try {
      val cred = credentialManager.getCredential(context, request).credential
      if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
        val token = GoogleIdTokenCredential.createFrom(cred.data).idToken
        Firebase.auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
        onAuthSuccess()
      } else {
        onUnauthenticated()
      }
    } catch (_: Exception) {
      onUnauthenticated()
    }
  }
}

fun onGoogleSignInClicked(
  context: Context,
  credentialManager: CredentialManager,
  onAuthSuccess: () -> Unit,
  onAuthError: (String) -> Unit,
  scope: CoroutineScope,
  onAuthCancelled: () -> Unit = {},
) {
  val clientId =
    try {
      context.getString(R.string.default_web_client_id)
    } catch (_: Exception) {
      onAuthError("Google Sign-In configuration missing: default_web_client_id not found")
      return
    }
  val activity = context as? Activity
  if (activity == null) {
    onAuthError("Unable to launch Google Sign-In without an active screen.")
    return
  }
  val auth = safeFirebaseAuth(context)
  if (auth == null) {
    onAuthError("Firebase authentication service is not ready yet. Please try again.")
    return
  }
  val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
  val request = GetCredentialRequest.Builder().addCredentialOption(signInOption).build()
  scope.launch {
    try {
      val cred = credentialManager.getCredential(activity, request).credential
      if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
        val token = GoogleIdTokenCredential.createFrom(cred.data).idToken
        auth.signInWithCredential(GoogleAuthProvider.getCredential(token, null)).await()
        onAuthSuccess()
      } else {
        onAuthError("Unexpected credential type returned.")
      }
    } catch (e: GetCredentialCancellationException) {
      Log.w(TAG, "Google Sign-In flow cancelled or dismissed: ${e.message}", e)
      onAuthCancelled()
    } catch (e: Exception) {
      Log.e(TAG, "Google Sign-In failed", e)
      onAuthError(e.localizedMessage ?: "Sign in failed. Please try again.")
    }
  }
}

fun signOutUser(
  credentialManager: CredentialManager,
  scope: CoroutineScope,
  onSignOutComplete: () -> Unit = {},
) {
  scope.launch {
    withContext(NonCancellable) {
      try {
        credentialManager.clearCredentialState(ClearCredentialStateRequest())
      } catch (e: Exception) {
        Log.w(TAG, "Failed to clear credential state: ${e.message}")
      } finally {
        runCatching { Firebase.auth.signOut() }
        onSignOutComplete()
      }
    }
  }
}

suspend fun deleteAuthenticatedFirebaseAccount(
  credentialManager: CredentialManager,
): Result<Unit> {
  return withContext(NonCancellable) {
    try {
      val currentUser = Firebase.auth.currentUser
        ?: return@withContext Result.failure(IllegalStateException("No active account found."))
      currentUser.delete().await()
      runCatching { credentialManager.clearCredentialState(ClearCredentialStateRequest()) }
      runCatching { Firebase.auth.signOut() }
      Result.success(Unit)
    } catch (e: com.google.firebase.auth.FirebaseAuthRecentLoginRequiredException) {
      Log.w(TAG, "Recent login required before account deletion", e)
      Result.failure(
        IllegalStateException("For security, please sign out and sign back in before deleting your account.")
      )
    } catch (e: Exception) {
      Log.e(TAG, "Account deletion failed", e)
      Result.failure(e)
    }
  }
}
